def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dataset", default=str(REPO / "dataset"))
    ap.add_argument("--report-dir", action="append", help="where to write the two reports (repeatable); default evaluation/ and code/evaluation/")
    ap.add_argument("--cache", help="developer cache of parsed evidence (never changes results)")
    args = ap.parse_args(argv)
    r = build(Path(args.dataset), args.cache)
    dirs = [Path(d) for d in args.report_dir] if args.report_dir else [REPO / "evaluation", HERE]
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)
        for name, body in (("evaluation_report.md", evaluation_report(r)), ("usage_report.md", usage_report())):
            with open(d / name, "w", encoding="utf-8", newline="\n") as handle:      # Path.write_text(newline=) needs Python 3.10
                handle.write(body)
        print("wrote %s and usage_report.md" % (d / "evaluation_report.md"))
    m = r["metrics"]
    print("samples: status %s, precision %s, recall %s, sequence %s | custom cases passed %d/%d | validator %s"
          % (pct(m["status_accuracy"]), pct(m["step_precision"]), pct(m["step_recall"]), pct(m["sequence_accuracy"]),
             sum(1 for c in r["custom"] if c["ok"]), len(r["custom"]), "PASS" if r["validator"].ok else "FAIL"))
    return 0 if r["validator"].ok and all(c["ok"] for c in r["custom"]) else 1


if __name__ == "__main__":
    sys.exit(main())
